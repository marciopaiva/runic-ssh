// Writes THIRD-PARTY-NOTICES.md: the licence text of every npm package that
// ships inside the frontend bundle, and of the two fonts.
//
// The Rust half is `cargo about` (see src-tauri/about.toml). This half exists
// because that tool does not read a pnpm lockfile. It uses `pnpm licenses`,
// which is already here, so it adds no dependency.
//
//   node scripts/third-party-notices.mjs          rewrite the file
//   node scripts/third-party-notices.mjs --check  fail if the file is stale
//
// A package whose licence file cannot be found is an error and not a silent
// gap, because a missing notice is the thing this file is for.

import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = join(root, 'THIRD-PARTY-NOTICES.md');
const check = process.argv.includes('--check');

const raw = execFileSync('pnpm', ['licenses', 'list', '--prod', '--json'], {
  cwd: root,
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
});

/** @type {{name: string, version: string, license: string, dir: string}[]} */
const packages = [];
for (const [license, list] of Object.entries(JSON.parse(raw))) {
  for (const entry of list) {
    entry.versions.forEach((version, i) => {
      packages.push({ name: entry.name, version, license, dir: entry.paths[i] });
    });
  }
}
packages.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const LICENCE_FILE = /^(licen[sc]e|copying|notice)(\.|-|_|$)/i;

function licenceText(dir) {
  const files = readdirSync(dir).filter((f) => LICENCE_FILE.test(f)).sort();
  return files.map((f) => readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n').trim());
}

const parts = [
  '# Third-party notices',
  '',
  'Generated by `scripts/third-party-notices.mjs`. Do not edit by hand.',
  'The Rust crates are in `THIRD-PARTY-LICENSES.html`.',
  '',
  '## npm packages in the frontend',
  '',
];

const missing = [];
for (const p of packages) {
  const texts = licenceText(p.dir);
  if (texts.length === 0) missing.push(`${p.name}@${p.version}`);
  parts.push(`### ${p.name} ${p.version} (${p.license})`, '');
  for (const t of texts) parts.push('```text', t, '```', '');
}

parts.push('## Fonts', '');
for (const [name, file] of [
  ['Manrope', 'OFL-Manrope.txt'],
  ['JetBrains Mono', 'OFL-JetBrainsMono.txt'],
]) {
  const path = join(root, 'src/styles/fonts', file);
  if (!existsSync(path)) missing.push(file);
  else parts.push(`### ${name} (OFL-1.1)`, '', '```text', readFileSync(path, 'utf8').replace(/\r\n/g, '\n').trim(), '```', '');
}

if (missing.length > 0) {
  console.error(`No licence file found for: ${missing.join(', ')}`);
  process.exit(1);
}

const text = parts.join('\n');
if (check) {
  const current = existsSync(output) ? readFileSync(output, 'utf8') : '';
  if (current !== text) {
    console.error('THIRD-PARTY-NOTICES.md is stale. Run: node scripts/third-party-notices.mjs');
    process.exit(1);
  }
  console.log(`ok    THIRD-PARTY-NOTICES.md covers ${packages.length} packages and 2 fonts`);
} else {
  writeFileSync(output, text);
  console.log(`wrote THIRD-PARTY-NOTICES.md (${packages.length} packages, 2 fonts)`);
}
