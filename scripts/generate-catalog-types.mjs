// Derives literal types from the source catalogue.
//
// TypeScript widens JSON string values to `string`, so a type read straight
// from `en.json` cannot see what a message says — which means it cannot see
// the placeholders inside it either. An earlier version of the catalogue
// claimed to type placeholders and did not: every key accepted no parameters
// at all, which looked like the feature working when it was the feature
// missing.
//
// `en.json` stays the source of truth, per section 1 of CLAUDE.md. This only
// restates it with `as const` so the compiler can read the strings, and it is
// regenerated by `pnpm typecheck` so it cannot drift from the JSON it mirrors.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const source = fileURLToPath(new URL('../src/locales/en.json', import.meta.url));
const target = fileURLToPath(
  new URL('../src/lib/i18n/catalog.generated.ts', import.meta.url),
);

const catalog = JSON.parse(readFileSync(source, 'utf8'));

const entries = Object.entries(catalog)
  .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
  .join('\n');

const output = `/* Generated from src/locales/en.json by scripts/generate-catalog-types.mjs.
 * Do not edit: run \`pnpm typecheck\`, which regenerates it.
 *
 * This exists only so the compiler can read what a message says. The runtime
 * catalogue is still the JSON — see src/lib/i18n/locales.ts. */

export const SOURCE_CATALOG = {
${entries}
} as const;
`;

writeFileSync(target, output);
